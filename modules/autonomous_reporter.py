    def execute(self, topic: str, recipient: Optional[str] = None, send_email: bool = False) -> Dict[str, Any]:
        t0 = time.time()
        research = self.research_topic(topic)
        pdf_path = self.build_pdf(research, topic)
        elapsed = round(time.time() - t0, 2)

        email_result = None
        if send_email or recipient:
            target_email = self.resolve_recipient_email(recipient or "ali")
            email_result = self.send_email_with_pdf(pdf_path, target_email, topic)

        return {
            "success": True,
            "topic": topic,
            "title": research.get("title"),
            "pdf_path": pdf_path,
            "filename": os.path.basename(pdf_path),
            "size_kb": round(os.path.getsize(pdf_path) / 1024, 1),
            "elapsed_sec": elapsed,
            "email_dispatched": bool(email_result and email_result.get("success")),
            "email_details": email_result,
            "summary": f"Report on '{topic}' generated in {elapsed}s and saved to {os.path.basename(pdf_path)}."
        }


