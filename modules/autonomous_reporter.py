    def resolve_recipient_email(self, recipient: str) -> Optional[str]:
        if not recipient:
            return None
        clean = recipient.strip().lower()
        if "@" in clean and "." in clean:
            return clean

        if os.path.exists(CONTACTS_PATH):
            try:
                with open(CONTACTS_PATH, "r", encoding="utf-8") as f:
                    contacts = json.load(f)
                    if clean in contacts:
                        val = contacts[clean]
                        if isinstance(val, dict) and "email" in val:
                            return val["email"]
                        elif isinstance(val, str) and "@" in val:
                            return val
            except Exception:
                pass

        return f"{clean}@gmail.com"

