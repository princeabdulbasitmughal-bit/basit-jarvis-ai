    def clean_text_for_pdf(self, text: Any) -> str:
        if not text:
            return ""
        if not isinstance(text, str):
            text = str(text)
        replacements = {
            '\u2018': "'", '\u2019': "'",
            '\u201c': '"', '\u201d': '"',
            '\u2013': '-', '\u2014': '--',
            '\u2011': '-', '\u2010': '-',
            '\u202f': ' ', '\u00a0': ' ',
            '\u2026': '...', '\u2022': '*',
            '\u25a0': '-', '\u25aa': '-',
            '•': '*', '–': '-', '—': '--',
            '’': "'", '‘': "'", '“': '"', '”': '"'
        }
        for orig, rep in replacements.items():
            text = text.replace(orig, rep)
        return text.encode('latin-1', 'replace').decode('latin-1')

